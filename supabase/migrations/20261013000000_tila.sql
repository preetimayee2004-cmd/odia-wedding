-- TILA wedding invitation: Wishing Wall + RSVP storage.
-- Run in Supabase → SQL Editor (or `supabase db push`).
--
-- Access model (enforced by row-level security, using the public anon key):
--   wishes  guests may add; everyone may read rows with status = 'visible'
--   rsvps   guests may add; NOBODY can read from the site — the couple reads
--           responses in the Supabase dashboard (Table editor → rsvps)

-- ── Wishes ──────────────────────────────────────────────────────
create table if not exists public.wishes (
  id          uuid primary key,                       -- generated by the browser: retries are idempotent
  name        text check (name is null or char_length(btrim(name)) between 1 and 60),
  message     text not null check (char_length(btrim(message)) between 2 and 280),
  -- Moderation: set a row to 'hidden' in the dashboard to remove it from the wall.
  -- For pre-moderation, change the default to 'pending' (and set
  -- wishes.requireApproval = true in src/config/wedding.ts), then approve rows
  -- by setting them to 'visible'.
  status      text not null default 'visible' check (status in ('visible', 'pending', 'hidden')),
  created_at  timestamptz not null default now()
);

create index if not exists wishes_visible_recent on public.wishes (created_at desc) where status = 'visible';

alter table public.wishes enable row level security;

drop policy if exists "Anyone can read visible wishes" on public.wishes;
create policy "Anyone can read visible wishes"
  on public.wishes for select to anon
  using (status = 'visible');

-- The site never sends a status, so new rows take the column default.
-- For pre-moderation, ALSO change this check to (status = 'pending') so a
-- hand-crafted request can't publish a wish directly.
drop policy if exists "Guests can add wishes" on public.wishes;
create policy "Guests can add wishes"
  on public.wishes for insert to anon
  with check (status in ('visible', 'pending'));

revoke update, delete on public.wishes from anon;

-- Light spam guard: reject an identical wish posted again within 10 minutes.
create or replace function public.reject_duplicate_wish() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if exists (
    select 1 from public.wishes
    where lower(btrim(message)) = lower(btrim(new.message))
      and coalesce(lower(btrim(name)), '') = coalesce(lower(btrim(new.name)), '')
      and created_at > now() - interval '10 minutes'
  ) then
    raise exception 'duplicate wish' using errcode = '23505';
  end if;
  return new;
end $$;

drop trigger if exists wishes_reject_duplicate on public.wishes;
create trigger wishes_reject_duplicate before insert on public.wishes
  for each row execute function public.reject_duplicate_wish();

-- ── RSVPs ───────────────────────────────────────────────────────
create table if not exists public.rsvps (
  id          uuid primary key,                       -- generated by the browser: double-submits are idempotent
  name        text not null check (char_length(btrim(name)) between 1 and 80),
  attending   boolean not null,
  attendees   smallint not null default 0 check (attendees between 0 and 10),
  message     text check (message is null or char_length(message) <= 500),
  guest_key   text check (guest_key is null or char_length(guest_key) <= 80),
  created_at  timestamptz not null default now(),
  check (attending or attendees = 0)
);

alter table public.rsvps enable row level security;

drop policy if exists "Guests can submit an RSVP" on public.rsvps;
create policy "Guests can submit an RSVP"
  on public.rsvps for insert to anon
  with check (true);

-- No select/update/delete policies for anon: responses stay private.
revoke select, update, delete on public.rsvps from anon;
